
# app/retrieval/vector_store.py

import logging
from pathlib import Path
from typing import Any, Sequence

import chromadb

from app.core.config import settings


logger = logging.getLogger(__name__)


class VectorStore:
    """
    ChromaDB adapter for persistent vector storage.

    Responsibilities:
    - Store embedded document chunks.
    - Search chunks using precomputed query embeddings.
    - Delete all chunks belonging to a document.
    - List indexed documents.

    Embeddings are generated by the ingestion/retrieval layers,
    not by ChromaDB.
    """

    def __init__(
        self,
        persist_directory: str | Path | None = None,
        collection_name: str | None = None,
    ) -> None:
        # Use application settings when available.
        default_path = getattr(
            settings,
            "vector_store_dir",
            Path("storage/vector_store"),
        )

        self.persist_directory = Path(
            persist_directory or default_path
        ).resolve()

        self.collection_name = (
            collection_name
            or getattr(
                settings,
                "collection_name",
                "documents",
            )
        )

        self.persist_directory.mkdir(
            parents=True,
            exist_ok=True,
        )

        # PersistentClient stores data on disk.
        self.client = chromadb.PersistentClient(
            path=str(self.persist_directory)
        )

        # Cosine distance is appropriate for normalized embeddings.
        self.collection = self.client.get_or_create_collection(
            name=self.collection_name,
            metadata={"hnsw:space": "cosine"},
        )

        logger.info(
            "Vector store initialized: path=%s, collection=%s",
            self.persist_directory,
            self.collection_name,
        )

    @staticmethod
    def _validate_chunks(chunks: Sequence[dict[str, Any]]) -> None:
        """Validate the minimum fields required for insertion."""

        if not chunks:
            raise ValueError("At least one chunk is required.")

        for index, chunk in enumerate(chunks):
            if not chunk.get("id"):
                raise ValueError(
                    f"Chunk at index {index} has no ID."
                )

            if not isinstance(chunk.get("text"), str):
                raise ValueError(
                    f"Chunk at index {index} has invalid text."
                )

            if not chunk["text"].strip():
                raise ValueError(
                    f"Chunk at index {index} has empty text."
                )

            embedding = chunk.get("embedding")

            if not isinstance(embedding, (list, tuple)):
                raise ValueError(
                    f"Chunk at index {index} has no embedding."
                )

            if not embedding:
                raise ValueError(
                    f"Chunk at index {index} has an empty embedding."
                )

            if not isinstance(chunk.get("metadata"), dict):
                raise ValueError(
                    f"Chunk at index {index} has invalid metadata."
                )

    def upsert_chunks(
        self,
        chunks: Sequence[dict[str, Any]],
        batch_size: int = 100,
    ) -> int:
        """
        Insert or update chunks in ChromaDB.

        Each chunk must contain:
            id, text, metadata, embedding

        Returns the number of chunks submitted successfully.
        """

        self._validate_chunks(chunks)

        if batch_size < 1:
            raise ValueError("batch_size must be positive.")

        # Validate embedding dimensions and numeric values.
        expected_dimension = len(chunks[0]["embedding"])

        if expected_dimension == 0:
            raise ValueError("Embedding dimension cannot be zero.")

        for index, chunk in enumerate(chunks):
            embedding = chunk["embedding"]

            if len(embedding) != expected_dimension:
                raise ValueError(
                    f"Chunk at index {index} has an inconsistent "
                    "embedding dimension."
                )

            for value in embedding:
                if (
                    isinstance(value, bool)
                    or not isinstance(value, (int, float))
                ):
                    raise ValueError(
                        f"Chunk at index {index} has a "
                        "non-numeric embedding value."
                    )

        total = 0

        # Process batches to avoid oversized ChromaDB requests.
        for start in range(0, len(chunks), batch_size):
            batch = chunks[start:start + batch_size]

            self.collection.upsert(
                ids=[str(chunk["id"]) for chunk in batch],
                documents=[chunk["text"] for chunk in batch],
                metadatas=[
                    {
                        key: value
                        for key, value in chunk["metadata"].items()
                        if value is not None
                        and isinstance(
                            value,
                            (str, int, float, bool),
                        )
                    }
                    for chunk in batch
                ],
                embeddings=[
                    [float(value) for value in chunk["embedding"]]
                    for chunk in batch
                ],
            )

            total += len(batch)

        logger.info("Upserted %d chunks.", total)

        return total

    def search_by_embedding(
        self,
        query_embedding: Sequence[float],
        top_k: int = 5,
        where: dict[str, Any] | None = None,
    ) -> list[dict[str, Any]]:
        """
        Retrieve the most similar chunks for a query embedding.

        query_embedding must be generated by the embedding model
        using the appropriate query format.

        Returns a flat list of chunks with cosine distances.
        """

        if not query_embedding:
            raise ValueError("Query embedding cannot be empty.")

        if top_k < 1:
            raise ValueError("top_k must be positive.")

        for value in query_embedding:
            if (
                isinstance(value, bool)
                or not isinstance(value, (int, float))
            ):
                raise ValueError(
                    "Query embedding must contain numeric values."
                )

        if self.collection.count() == 0:
            return []

        query_vector = [
            float(value) for value in query_embedding
        ]

        # Detect dimension mismatches before querying.
        stored = self.collection.peek(limit=1)

        if stored["embeddings"] is not None and len(
            stored["embeddings"]
        ):
            stored_dimension = len(stored["embeddings"][0])

            if len(query_vector) != stored_dimension:
                raise ValueError(
                    "Query embedding dimension does not match "
                    "the stored document embeddings."
                )

        query_args: dict[str, Any] = {
            "query_embeddings": [query_vector],
            "n_results": min(top_k, self.collection.count()),
            "include": [
                "documents",
                "metadatas",
                "distances",
            ],
        }

        if where:
            query_args["where"] = where

        results = self.collection.query(**query_args)

        ids = results["ids"][0]
        documents = results["documents"][0]
        metadatas = results["metadatas"][0]
        distances = results["distances"][0]

        return [
            {
                "id": chunk_id,
                "text": text,
                "metadata": metadata or {},
                "distance": distance,
            }
            for chunk_id, text, metadata, distance in zip(
                ids,
                documents,
                metadatas,
                distances,
            )
        ]

    def delete_document(self, doc_id: str) -> int:
        """
        Delete every indexed chunk belonging to a document.

        Returns the number of chunks deleted.
        """

        if not doc_id.strip():
            raise ValueError("doc_id cannot be empty.")

        existing = self.collection.get(
            where={"doc_id": doc_id},
            include=["metadatas"],
        )

        ids = existing["ids"]

        if not ids:
            return 0

        self.collection.delete(ids=ids)

        logger.info(
            "Deleted %d chunks for document %s.",
            len(ids),
            doc_id,
        )

        return len(ids)

    def list_documents(self) -> list[dict[str, Any]]:
        """
        Return a summary of documents represented in the collection.

        Document metadata is derived from the indexed chunks.
        """

        result = self.collection.get(
            include=["metadatas"],
        )

        documents: dict[str, dict[str, Any]] = {}

        for metadata in result["metadatas"]:
            metadata = metadata or {}
            doc_id = metadata.get("doc_id")

            if not doc_id:
                continue

            if doc_id not in documents:
                documents[doc_id] = {
                    "doc_id": doc_id,
                    "file_name": metadata.get("file_name"),
                    "file_type": metadata.get("file_type"),
                    "chunk_count": 0,
                }

            documents[doc_id]["chunk_count"] += 1

        return list(documents.values())

    def count_chunks(self) -> int:
        """Return the total number of indexed chunks."""
        return self.collection.count()

    def close(self) -> None:
        """Release the client reference."""
        self.client = None
        self.collection = None


